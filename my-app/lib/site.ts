// 客户端安全的站点配置（不依赖 Node.js fs）
export type Lang = "zh" | "en";

export interface PostFrontmatter {
  title: string;
  date: string;
  draft?: boolean;
  author?: string;
  tags?: string[];
  categories?: string[];
  summary?: string;
  description?: string;
  pinned?: boolean;
  /* 卡组内文章的手动排序号；不写则按文件名数字前缀排 */
  order?: number;
  /* 作为「关于」文章：正文会渲染在首页首屏，并不再出现在下方展示位里 */
  about?: boolean;
  pinnedDescription?: string;
  hiddenInHomeList?: boolean;
  showToc?: boolean;
  cover?: { image?: string; caption?: string; hidden?: boolean; relative?: boolean };
  references?: { title: string; url?: string; author?: string; year?: string }[];
  keywords?: string[];
  canonicalURL?: string;
}

export interface Post {
  slug: string;
  lang: Lang;
  title: string;
  date: string;
  author?: string;
  tags: string[];
  categories: string[];
  summary: string;
  description?: string;
  pinned: boolean;
  about: boolean;
  /* 所属卡组的目录名；不属于任何卡组时为 undefined */
  group?: string;
  /* 卡组内的排序号（frontmatter 的 order） */
  order?: number;
  /* 卡片右侧缩略图：优先 frontmatter 的 cover.image，否则取正文第一张图。
     两者都没有则为 undefined，卡片不渲染图片。 */
  thumbnail?: string;
  pinnedDescription?: string;
  hiddenInHomeList: boolean;
  showToc: boolean;
  cover?: PostFrontmatter["cover"];
  references?: PostFrontmatter["references"];
  keywords?: string[];
  content: string;
  filePath: string;
  wordCount: number;
  isAI: boolean;
}

/* ===== 卡组（文章组） =====
   由 content/<lang>/posts/<组名>/_index.md 标记，同目录下的 .md 即组内文章。
   组本身没有日期，用组内最新文章的时间去列表里定位。 */
export interface PostGroup {
  /** 目录名，也是 URL 片段 */
  slug: string;
  lang: Lang;
  title: string;
  description?: string;
  /** 组内最新一篇文章的日期，用于列表排序 */
  date: string;
  /** 封面图：_index.md 的 cover.image，填满卡片边框内部 */
  cover?: string;
  /** 已按 order / 文件名前缀排好序的组内文章 */
  posts: Post[];
  wordCount: number;
}

