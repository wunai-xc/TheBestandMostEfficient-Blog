// 阅读时长（分钟）：按 400 字/分钟估算，至少 1 分钟
export const WORDS_PER_MINUTE = 400;

export function readingMinutes(wordCount: number): number {
  return Math.max(1, Math.round(wordCount / WORDS_PER_MINUTE));
}
